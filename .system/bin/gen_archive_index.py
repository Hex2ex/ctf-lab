#!/usr/bin/env python3
"""Writes INDEX.md for every real-CTF archive (catalog category 'archives'): one table per category,
listing each challenge, its year/event, its path and whether it ships a solution/write-up.

Usage: gen_archive_index.py [archive-id ...]   (default: all archives)
Layouts understood:
  google   <year>/<event>/<category>-<name>/...      (event = quals, finals, beginners, hackceler8)
  ductf25  <category>/<name>/...
  ctfwiki  <category>/<topic>/<challenge>/...
"""
import os, re, sys

SYS = os.path.realpath(os.path.join(os.path.dirname(os.path.realpath(__file__)), ".."))
ROOT = os.path.dirname(SYS)
LEVEL = {"1": "1-easy", "2": "2-medium", "3": "3-hard"}
SOLUTION_RE = re.compile(r"(solve|solution|writeup|write-up|exploit|sol\.|healthcheck|flag)", re.I)
CAT_NAMES = {"pwn": "Pwn", "rev": "Reverse", "reverse": "Reverse", "re": "Reverse", "crypto": "Crypto", "web": "Web", "misc": "Misc",
             "forensics": "Forensics", "beginner": "Beginner", "osint": "OSINT", "ai": "AI", "sandbox": "Sandbox", "hw": "Hardware",
             "hardware": "Hardware", "blockchain": "Blockchain", "android": "Android", "executable": "Executables", "ics": "ICS",
             "survey": "Survey", "game": "Game"}


def visible(path):
    try:
        return sorted(e for e in os.listdir(path) if not e.startswith(".") and os.path.isdir(os.path.join(path, e)))
    except OSError:
        return []


def has_solution(path, depth=3):
    for cur, dirs, files in os.walk(path):
        if cur[len(path):].count(os.sep) >= depth:
            dirs[:] = []
        dirs[:] = [d for d in dirs if not d.startswith(".")]
        if any(SOLUTION_RE.search(f) for f in files) or any(SOLUTION_RE.search(d) for d in dirs):
            return True
    return False


def cat_name(c):
    return CAT_NAMES.get(c.lower(), c.replace("_", " ").title() if c.isascii() else c)


def scan_google(base):
    rows = []
    for year in visible(base):
        if not re.fullmatch(r"20\d\d", year):
            continue
        for event in visible(os.path.join(base, year)):
            ev = os.path.join(base, year, event)
            if event == "hackceler8":
                rows.append(("game", "hackceler8", f"{year} {event}", f"{year}/{event}", has_solution(ev)))
                continue
            for ch in visible(ev):
                m = re.match(r"^([a-z]+)-(.+)$", ch)
                cat, name = (m.group(1), m.group(2)) if m else ("other", ch)
                rows.append((cat, name, f"{year} {event}", f"{year}/{event}/{ch}", has_solution(os.path.join(ev, ch))))
    return rows


def scan_flat(base):
    rows = []
    for cat in visible(base):
        for ch in visible(os.path.join(base, cat)):
            rows.append((cat, ch, "2025", f"{cat}/{ch}", has_solution(os.path.join(base, cat, ch))))
    return rows


def scan_topics(base):
    rows = []
    for cat in visible(base):
        for topic in visible(os.path.join(base, cat)):
            subs = visible(os.path.join(base, cat, topic))
            if not subs:
                rows.append((cat, topic, topic, f"{cat}/{topic}", has_solution(os.path.join(base, cat, topic))))
            for ch in subs:
                rows.append((cat, ch, topic, f"{cat}/{topic}/{ch}", has_solution(os.path.join(base, cat, topic, ch))))
    return rows


SCANNERS = {"google": (scan_google, "Year / event"), "ductf25": (scan_flat, "Year"), "ctfwiki": (scan_topics, "Topic")}


def md_link(path):
    return "<" + path + "/>"


def write_index(lab_id, name, base):
    scan, col = SCANNERS.get(lab_id, (scan_flat, "Group"))
    rows = scan(base)
    by_cat = {}
    for r in rows:
        by_cat.setdefault(r[0], []).append(r)
    out = [f"# {name} — challenge index", "",
           f"{len(rows)} challenges in {len(by_cat)} categories. ✓ = the folder ships a solution, exploit or write-up.",
           "Generated by `.system/bin/gen_archive_index.py`; rerun it after updating the archive.", ""]
    out += ["| Category | Challenges |", "|---|---|"] + [f"| [{cat_name(c)}](#{cat_name(c).lower().replace(' ', '-').replace('/', '')}) | {len(v)} |" for c, v in sorted(by_cat.items())] + [""]
    for c, v in sorted(by_cat.items()):
        out += [f"## {cat_name(c)}", "", f"| Challenge | {col} | Path | Solution |", "|---|---|---|---|"]
        for _, ch, grp, path, sol in sorted(v, key=lambda r: (r[2], r[1])):
            out.append(f"| {ch.replace('|', '/')} | {grp.replace('|', '/')} | [{path.replace('|', '/')}]({md_link(path)}) | {'✓' if sol else ''} |")
        out.append("")
    with open(os.path.join(base, "INDEX.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    return len(rows)


def main(ids):
    with open(os.path.join(SYS, "catalog", "labs.psv"), encoding="utf-8") as f:
        archives = [l.split("|") for l in f if l.strip() and not l.startswith("#") and l.split("|")[2:3] == ["archives"]]
    for a in archives:
        if ids and a[0] not in ids:
            continue
        base = os.path.join(ROOT, "08-archives", LEVEL.get(a[3], "0-unrated"), a[0])
        if os.path.isdir(base):
            print(f"{a[0]}: {write_index(a[0], a[4], base)} challenges → {base}/INDEX.md")


if __name__ == "__main__":
    main(sys.argv[1:])
